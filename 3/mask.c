#include <stdint.h>

/* bit    7        6        5        4         3        2       1      0    */
#define FLAG_READY     (1u << 7)   /* 0x80  1000 0000 */
#define FLAG_IMU_OK    (1u << 6)   /* 0x40  0100 0000 */
#define FLAG_CAN_ERR   (1u << 5)   /* 0x20  0010 0000 */
#define FLAG_OVERHEAT  (1u << 4)   /* 0x10  0001 0000 */
#define FLAG_LOW_VOLT  (1u << 3)   /* 0x08  0000 1000 */
#define FLAG_ESTOP     (1u << 2)   /* 0x04  0000 0100 */
#define FLAG_M2_EN     (1u << 1)   /* 0x02  0000 0010 */
#define FLAG_M1_EN     (1u << 0)   /* 0x01  0000 0001 */

uint8_t status = 0u;               /* 0x00  0000 0000 */
/* ---------- 掩码：只选中 bit3 这一位 ----------
 * 掩码      1u << 3   = 0x08  0000 1000
 * 取反掩码  ~(1u << 3) = 0xF7  1111 0111   只有 bit3 是 0，其余全是 1
 * ------------------------------------------------ */

/* ---------- ① 置位：用掩码把 bit3 变 1，其他位不动 ---------- */
status |= FLAG_LOW_VOLT;                    /* 0x00 -> 0x08   0000 0000 -> 0000 1000 */

/* ---------- ② 再置一位，已有位不受影响 ---------- */
status |= FLAG_M1_EN;                       /* 0x08 -> 0x09   0000 1000 -> 0000 1001 */

/* ---------- ③ 清位：& 上取反掩码，把 bit3 变 0，其他位不动 ---------- */
status &= (uint8_t)(~FLAG_LOW_VOLT);        /* 0x09 -> 0x01   0000 1001 -> 0000 0001 */
/*   0000 1001
 * & 1111 0111
 * = 0000 0001       ← 只有 bit3 被清掉 */

/* ---------- ④ 取位：判断某一位是不是 1 ---------- */
if (status & FLAG_M1_EN)                    /* 0000 0001 & 0000 0001 = 非 0 → 真 */
{
    /* M1 已使能 */
}

/* ---------- ⑤ 掩码抠字段：取 bit4~bit2 共 3 位 ---------- */
uint8_t mode;
mode = (status >> 2) & 0x07;                /* 0x07 = 0000 0111，3 位宽的掩码 */

/* ---------- ⑥ 掩码改字段：先清后置 ---------- */
status = (uint8_t)((status & (uint8_t)~(0x07u << 2)) | ((uint32_t)mode << 2));
/*                   ↑ 把 bit4~bit2 清 0        ↑ 再把新值放回去 */